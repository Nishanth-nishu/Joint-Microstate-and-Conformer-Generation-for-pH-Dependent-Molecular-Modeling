"""E1 conformer component: state-conditioned generators against reference ensembles, where references exist.

Only GEOM-QM9 test molecules have reference ensembles here; they are neutral and inside TD-qm9's domain, so this
measures p(x | z) quality for neutral in-distribution states only (no charged or tautomeric state has a reference).
Arms (same molecules, same budget 2 x n_true, same per-conformer RDKit seeds, scored by TD's evaluate_confs.py):
  td      jmcg.condgen.fidelity wrapper (TDGenerator, qm9_default)          [generated by fidelity.py wrapper]
  etkdg   ETKDGv3, no force-field refinement (TD's seeds are unrefined too)  [this file]
  etkdg_mmff  ETKDGv3 + MMFF94s minimisation: a separate, labelled ablation, not the fair comparison
Run (TD venv): python -m jmcg.condgen.e1_confs etkdg --subset subset.csv --seed 0 [--mmff] --out etkdg0.pkl
               python -m jmcg.condgen.e1_confs compare --ref td0.eval.pkl td1.eval.pkl --arm etkdg0.eval.pkl ... --out c.json
"""
import argparse
import json
import pickle

import numpy as np
import pandas as pd
from rdkit import Chem
from rdkit.Chem import AllChem

from jmcg.condgen.td_backend import etkdg_baseline

THRS = (0.25, 0.5, 0.75)


def cmd_etkdg(a):
    out, fails = {}, []
    for raw, n_true, smi in pd.read_csv(a.subset).values:
        try:
            mols = etkdg_baseline(Chem.AddHs(Chem.MolFromSmiles(smi)), 2 * int(n_true), a.seed)
            if a.mmff:
                for m in mols:
                    AllChem.MMFFOptimizeMolecule(m, mmffVariant='MMFF94s', maxIters=2000)
            out[smi] = mols
        except Exception as e:  # noqa: BLE001 - counted as a model failure by evaluate_confs.py
            fails.append((smi, f'{type(e).__name__}: {e}'[:200]))
    pickle.dump(out, open(a.out, 'wb'))
    print(f'etkdg{"+mmff" if a.mmff else ""} seed {a.seed}: {len(out)} molecules, {len(fails)} failures {fails[:5]}')


def per_mol(path):
    d = pickle.load(open(path, 'rb'))
    rows, n_nan = {}, 0
    for (smi, csmi), r in d['results'].items():
        m = r['rmsd']
        if np.isnan(m).any():  # an alignment evaluate_confs.py could not do; dropped here, so absent from the paired set
            n_nan += 1
            continue
        row = dict(MAT_R=float(np.min(m, axis=1).mean()), MAT_P=float(np.min(m, axis=0).mean()))
        for t in THRS:
            row[f'COV_R@{t}'] = float(np.mean(np.min(m, axis=1) < t) * 100)
            row[f'COV_P@{t}'] = float(np.mean(np.min(m, axis=0) < t) * 100)
        rows[csmi] = row
    return pd.DataFrame.from_dict(rows, orient='index'), dict(model_failures=d['num_failures'], rmsd_nan_dropped=n_nan)


def cmd_compare(a):
    rng = np.random.default_rng(0)
    arms = {p: per_mol(p) for p in a.ref + a.arm}
    common = set.intersection(*[set(v[0].index) for v in arms.values()])
    idx = sorted(common)
    res = dict(n_common=len(idx), failures={p: v[1] for p, v in arms.items()}, arms={})
    for p, (df, _) in arms.items():
        res['arms'][p] = {c: float(df.loc[idx, c].mean()) for c in df.columns}
    ref = sum(arms[p][0].loc[idx] for p in a.ref) / len(a.ref)
    res['paired_arm_minus_ref'] = {}
    for p in a.arm:
        df = arms[p][0].loc[idx]
        out = {}
        for c in df.columns:
            dlt = (df[c] - ref[c]).to_numpy()
            bs = [dlt[rng.integers(0, len(dlt), len(dlt))].mean() for _ in range(5000)]
            out[c] = dict(mean=float(dlt.mean()), ci95=[float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))])
        res['paired_arm_minus_ref'][p] = out
    json.dump(res, open(a.out, 'w'), indent=1)
    print(json.dumps(res, indent=1)[:6000])


def main():
    ap = argparse.ArgumentParser()
    sp = ap.add_subparsers(dest='cmd', required=True)
    s = sp.add_parser('etkdg')
    s.add_argument('--subset', required=True); s.add_argument('--seed', type=int, default=0)
    s.add_argument('--mmff', action='store_true'); s.add_argument('--out', required=True)
    s = sp.add_parser('compare')
    s.add_argument('--ref', nargs='+', required=True); s.add_argument('--arm', nargs='+', required=True)
    s.add_argument('--out', required=True)
    a = ap.parse_args()
    dict(etkdg=cmd_etkdg, compare=cmd_compare)[a.cmd](a)


if __name__ == '__main__':
    main()
