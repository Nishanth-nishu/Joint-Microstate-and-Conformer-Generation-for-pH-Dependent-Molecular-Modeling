"""Subset generation and splicing (EXP-3 §9.1, accepted with conditions; Q-P1-006 item 1, Q-P3-004 item 3).

Every Stage A operator is the identity on molecules without a constrained bond, so an arm is generated only on the
affected molecules and O's conformers (same seed, same per-conformer streams) fill every other molecule. Conditions
(§9.1): per-conformer seeding (``seeding.py``); O regenerated with that seeding; a bit-identity test of the arm against
O on unaffected molecules (``unaffected_deviation``: 0 on CPU, reported on GPU); absolute levels from one source.
"""
from __future__ import annotations

import argparse
import pickle

import numpy as np


def splice(o_confs: dict, arm_confs: dict, affected: set[str]) -> dict:
    """O's molecules with the affected ones replaced by the arm's. A molecule that failed in the arm stays a failure
    (it is removed), so failure sets are the arm's own on the subset."""
    extra = set(arm_confs) - affected
    if extra:
        raise ValueError(f'{len(extra)} arm molecules outside the affected set, e.g. {sorted(extra)[:3]}')
    out = {k: v for k, v in o_confs.items() if k not in affected}
    out.update({k: arm_confs[k] for k in affected if k in arm_confs})
    return out


def unaffected_deviation(o_confs: dict, arm_confs: dict) -> float:
    """Largest coordinate difference (Å) between arm and O over molecules generated by both (bit-identity check);
    raises if they share no molecule (the check would be vacuous)."""
    worst = 0.0
    shared = set(o_confs) & set(arm_confs)
    if not shared:
        raise ValueError('identity check is vacuous: arm and O share no molecule')
    for k in shared:
        for a, b in zip(o_confs[k], arm_confs[k]):
            worst = max(worst, float(np.abs(a.GetConformer().GetPositions() - b.GetConformer().GetPositions()).max()))
    return worst


def prefix(pool: dict, n_conf: dict[str, int], mult: int = 2) -> dict:
    """The first ``mult`` × K conformers of every pooled molecule: with per-conformer streams this IS the 2K run of the
    same seed (EXP-5 §12.1: "Columns [0, 2K_i) are P0"), so Exp 3's O comes from Exp 5's pools without new GPU time."""
    out = {}
    for k, mols in pool.items():
        need = mult * n_conf[k]
        if len(mols) < need:
            raise ValueError(f'{k}: pool has {len(mols)} < {need} conformers')
        out[k] = mols[:need]
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description='Splice an affected-subset arm into O, or cut O from a pool (EXP-3 §9.1)')
    sub = ap.add_subparsers(dest='cmd', required=True)
    sp = sub.add_parser('splice')
    sp.add_argument('--o_confs', required=True)
    sp.add_argument('--arm_confs', required=True)
    sp.add_argument('--keys', required=True)
    sp.add_argument('--out', required=True)
    sp.add_argument('--identity_check', default=None,
                    help='confs.pkl of the arm run on UNAFFECTED molecules: must equal O there (§9.1 condition 3)')
    pp = sub.add_parser('prefix')
    pp.add_argument('--pool', required=True)
    pp.add_argument('--csv', required=True)
    pp.add_argument('--out', required=True)
    a = ap.parse_args()
    if a.cmd == 'prefix':
        import pandas as pd
        df = pd.read_csv(a.csv)
        with open(a.pool, 'rb') as f:
            pool = pickle.load(f)
        with open(a.out, 'wb') as f:
            pickle.dump(prefix(pool, dict(zip(df.corrected_smiles, df.n_conformers.astype(int)))), f)
        print(f'SUMMARY prefix 2K of {len(pool)} pooled molecules')
        return
    with open(a.o_confs, 'rb') as f:
        o = pickle.load(f)
    with open(a.arm_confs, 'rb') as f:
        arm = pickle.load(f)
    keys = {ln.strip() for ln in open(a.keys) if ln.strip()}
    with open(a.out, 'wb') as f:
        pickle.dump(splice(o, arm, keys), f)
    dev = ''
    if a.identity_check:
        with open(a.identity_check, 'rb') as f:
            dev = f'; unaffected max deviation vs O {unaffected_deviation(o, pickle.load(f)):.2e} A'
    print(f'SUMMARY splice affected {len(keys)}; arm molecules {len(arm)}; O molecules {len(o)}{dev}')


if __name__ == '__main__':
    main()
